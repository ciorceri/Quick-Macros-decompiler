#!/usr/bin/env python3
"""Regenerates docs/OPCODES.md from the analysis JSON files.

Inputs are analysis/opcode_semantics.json, analysis/layout_final.json and
analysis/unseen_opcodes.json.

Usage:
    python tools/gen_opcodes.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
A = ROOT / "analysis"
sem = json.load(open(A / "opcode_semantics.json", encoding="utf-8"))
lay = json.load(open(A / "layout_final.json", encoding="utf-8"))
unseen = json.load(open(A / "unseen_opcodes.json", encoding="utf-8"))


def status(c: str | None) -> str:
    """Maps a confidence string to a status word for the table.

    Args:
      c: Confidence text from the semantics JSON (may be None or empty).

    Returns:
      The status word, or the lowercased text itself ("?" if empty) when
      it matches no known prefix.
    """
    c = (c or "").lower()
    if c.startswith("observed"):
        return (
            "observed"
            if "inferred" not in c
            else "observed (layout) / inferred (meaning)"
        )
    if c.startswith("inferred"):
        return "inferred"
    return (
        "observed (layout) / inferred (meaning)"
        if c.startswith("layout") or c.startswith("observed")
        else c or "?"
    )


def cell(s: object, n: int = 260) -> str:
    """Formats a value as a single-line markdown table cell.

    Args:
      s: The value; falsy values give an empty cell.
      n: Maximum length, including the trailing "..." of a truncation.

    Returns:
      The text with whitespace collapsed and "|" replaced by "/".
    """
    s = " ".join(str(s or "").split()).replace("|", "/")
    return s if len(s) <= n else s[: n - 3] + "..."


def keyorder(k: str) -> tuple[str, int, str]:
    """Sort key for semantic keys of the form `<prefix>:<hex opcode>[#n]`.

    Args:
      k: The semantic key.

    Returns:
      Tuple (prefix, opcode value or 0 if not hex, text after the colon).
    """
    pre, _, op = k.partition(":")
    base = op.split("#")[0]
    try:
        return (pre, int(base, 16), op)
    except ValueError:
        return (pre, 0, op)


out = [
    "# OPCODES",
    "",
    "Generated by `python tools/gen_opcodes.py` from "
    "`analysis/opcode_semantics.json` (facts about the QM",
    "bytecode and runtime), `analysis/layout_final.json` and "
    "`analysis/unseen_opcodes.json`. Do not edit by hand:",
    "change the JSON and regenerate.",
    "",
    "Status words:",
    "",
    "* **observed** - bytes seen in real exes AND the matching `.qml` source "
    "(or handler + QM help page) agree.",
    "* **inferred** - plausible from one occurrence / statement order / "
    "handler only; the meaning is not proven.",
    "* **handler-only** - read from the runtime handler; no sample in the "
    "corpus exercises it (see the last table).",
    "",
    "Layout notation: an integer is a count of raw bytes (opcode byte "
    "included); `S` = nested table-1 instruction; `T2` = table-2",
    "operator instruction; other tokens (`ARGN`, `X_*`, `IF` ...) are "
    "extension tokens implemented in `qmlayout.py`.",
    "Evidence strings are truncated here; the full text is in the JSON.",
    "",
]
groups = {
    "T1": "Table 1 (statements and expressions)",
    "T2": "Table 2 (operators)",
    "T2via37": (
        "Table 2 operators reached through opcode 0x37 (string/format methods)"
    ),
    "ARG": "Argument prefixes",
}
for pre, title in groups.items():
    ks = sorted((k for k in sem if k.partition(":")[0] == pre), key=keyorder)
    if not ks:
        continue
    out += [
        f"## {title} - {len(ks)} entries",
        "",
        "| opcode | name | layout | status | evidence |",
        "|---|---|---|---|---|",
    ]
    for k in ks:
        v = sem[k]
        lt = v.get("layout_tokens")
        layout = " ".join(str(x) for x in lt) if lt else v.get("operands", "")
        if pre == "T1" and not lt:
            lk = k.partition(":")[2]
            lt2 = (
                lay.get(str(int(lk.split("#")[0], 16)))
                if "#" not in lk
                else None
            )
            if lt2:
                layout = " ".join(str(x) for x in lt2)
        out.append(
            f"| `{k.partition(':')[2]}` | {cell(v.get('name'), 40)} "
            f"| `{cell(layout, 80)}` | {status(v.get('confidence'))} "
            f"| {cell(v.get('evidence'))} |"
        )
    out.append("")
out += [
    "## Valid table-1 opcodes never seen in any statement of the reference "
    f"corpus - {len(unseen)} entries",
    "",
    "Layout and behaviour come from the handler code only (status: "
    "handler-only). Command names are inferred. Adding a sample",
    "that exercises one of them (see CONTRIBUTING.md) turns it into an "
    "observed entry.",
    "",
    "| opcode | alias of | classification | behaviour (truncated) |",
    "|---|---|---|---|",
]
for k in sorted(unseen, key=lambda x: int(x, 16)):
    v = unseen[k]
    out.append(
        f"| `{k}` | {v.get('alias_of') or ''} "
        f"| {v.get('classification', '')} "
        f"| {cell(v.get('behaviour'), 200)} |"
    )
out.append("")
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "OPCODES.md").write_text("\n".join(out), encoding="utf-8")
print(
    "wrote docs/OPCODES.md:",
    sum(1 for _ in sem),
    "semantic entries,",
    len(unseen),
    "unseen",
)
