#!/usr/bin/env python3
"""make_roundtrip.py - turn the 35 compile samples (exe) into compilable QML via qmdec.

original exe -> qmdec -> roundtrip/<name>.qml -> (user: Quick Macros Make Exe) -> compare_roundtrip.py

Only user code is emitted (macro + its `#sub`s = res3 names `<parentid>Name`); embedded
library functions (System.qml stdlib copies, kind 7 stubs) are re-created by QM itself.
A sample is marked NOT ROUNDTRIPPABLE when its decompiled code (outside comments) still
contains something that is not legal QM: TODO(evidence) markers, `type_<id>` user types
(the `type` declaration, member names and sizes are not stored in the exe), `op_0x`.

Usage: python make_roundtrip.py [--out roundtrip]
"""
import argparse, re, subprocess, sys, tempfile, uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SECT = re.compile(r"^; ---- function (.+?) \(res2 id (\d+), kind (\d+)\) ----$")
GLOBDECL = re.compile(r"^(int|str)\+ glob(\d+)\b")


def code_part(line):
    """line without its trailing `;;note` (first ;; outside a string literal)"""
    instr = False
    for i, c in enumerate(line):
        if c == '"':
            instr = not instr
        elif not instr and line.startswith(";;", i):
            return line[:i]
    return line


def decompile_text(exe, tmp):
    out = Path(tmp) / (exe.stem + ".qmdec.qml")
    subprocess.run([sys.executable, str(ROOT / "qmdec.py"), str(exe), "-o", str(out), "--roundtrip"],
                   check=True, cwd=ROOT, capture_output=True)
    return out.read_text(encoding="utf-8").split("\n")


def split_sections(lines):
    pre, secs, cur = [], [], None
    for ln in lines:
        m = SECT.match(ln)
        if m:
            cur = {"name": m.group(1), "id": int(m.group(2)), "kind": int(m.group(3)), "body": []}
            secs.append(cur)
        elif cur is None:
            pre.append(ln)
        elif ln.startswith("; statements:") or ln.startswith("; user code only"):
            continue
        else:
            cur["body"].append(ln)
    for s in secs:
        while s["body"] and not s["body"][-1].strip():
            s["body"].pop()
        while s["body"] and not s["body"][0].strip():
            s["body"].pop(0)
    return pre, secs


def blockers(body):
    why = []
    for ln in body:
        if ln.startswith(";"):
            if "TODO(evidence" in ln:
                why.append("unresolved statement: " + ln[:90])
            continue
        c = code_part(ln)
        if "TODO" in c:
            why.append("TODO in code: " + c.strip()[:80])
        for m in set(re.findall(r"\btype_[0-9a-f]+\b", c)):
            why.append(f"user type `{m}`: `type` declaration, name and member list are not stored in the exe "
                       "(only member offsets seen in use; unused members/padding/total size not provable)")
        if re.search(r"\bop_0x", c):
            why.append("op_0x placeholder: " + c.strip()[:80])
        if "/*" in c:
            why.append("unfinalised note token: " + c.strip()[:80])
    return list(dict.fromkeys(why))


def build(exe, outdir):
    with tempfile.TemporaryDirectory() as tmp:
        lines = decompile_text(exe, tmp)
    pre, secs = split_sections(lines)
    globs = {}
    for ln in pre:
        m = GLOBDECL.match(ln)
        if m:
            globs[int(m.group(2))] = code_part(ln).rstrip()
    main = next((s for s in secs if s["kind"] == 1), None)
    if main is None:
        return None, ["no kind-1 (macro) function found"], 0
    pfx = f"<{main['id']:05d}>"
    user = [main] + [s for s in secs if s["kind"] == 2 and s["name"].startswith(pfx)]
    reasons, out, ncode = [], [], 0
    out.append(f"; round-trip source generated by make_roundtrip.py from {exe.name} via qmdec.py")
    out.append("; Local names are neutral (loc<i> / glob<id>); `;;` notes are qmdec annotations (comments).")
    out.append("")
    for k, s in enumerate(user):
        body = list(s["body"])
        reasons += [f"{s['name']}: {w}" for w in blockers(body)]
        sub_attr = ""
        if any("parent_loc" in code_part(b) for b in body):
            allcode = " ".join(code_part(b) for b in body)
            own = set(re.findall(r"(?<!parent_)\bloc(\d+)\b", allcode))
            par = set(re.findall(r"\bparent_loc(\d+)\b", allcode))
            if own & par:
                reasons.append(f"{s['name']}: parent variable loc{sorted(own & par)[0]} collides with a local of the #sub")
            body = [b if b.startswith(";") else re.sub(r"\bparent_loc(\d+)\b", r"loc\1", b) for b in body]
            sub_attr = " v"
        used = sorted({int(g) for b in body for g in re.findall(r"\bglob(\d+)\b", code_part(b))})
        decl = [globs[g] for g in used if g in globs]
        missing = [g for g in used if g not in globs]
        if missing:
            reasons.append(f"{s['name']}: glob{missing[0]} used but its res10 declaration is unknown")
        at = 1 if body and code_part(body[0]).lstrip().startswith("function") else 0
        body[at:at] = decl                          # declarations right after the `function` line
        if k:
            nm = s["name"][len(pfx):]
            out.append(f"#sub {nm}{sub_attr}")
        out += body
        out.append("")
        ncode += sum(1 for b in body if b.strip() and not b.startswith(";"))
    out.append("")
    foot = [" BEGIN PROJECT", " main_function  Macro1", f" exe_file  $desktop$\\roundtrip\\{exe.stem}.exe",
            " icon  <default>", " manifest  $qm$\\default.exe.manifest", " flags  6",
            " guid  {" + str(uuid.uuid4()).upper() + "}", " END PROJECT"]
    text = "\r\n".join(out + foot) + "\r\n"
    return text, reasons, ncode


README_HEAD = """# roundtrip - decompile -> recompile -> compare

Goal: original exe -> `qmdec.py` -> `roundtrip/<name>.qml` -> YOU compile it in Quick Macros 2.4.12
(Make Exe) -> `compare_roundtrip.py` compares the new exe's bytecode with the original's. If they
match, the decompiler output for that sample is proven faithful.

## How to compile (same procedure as samples/README.md)
1. In QM 2.4.12 create ONE new macro per file and paste the whole content of `roundtrip/<name>.qml`
   (the `BEGIN PROJECT` footer is the file-properties block; keep it as in the files).
2. Compile / Make Exe so that the exe lands in `$desktop$\\roundtrip\\<name>.exe`; copy those exes
   back into this folder (`roundtrip/`). Do NOT run the exes.
3. If a line fails: put `;;` at the START of that line (a trailing comment does NOT disable it),
   write the error text to `<name>.error`, recompile and send the exe anyway. The error offset `/NNN`
   is the start of the failing line.
4. Start with the first 10 files of the table (sorted simplest first).
5. Then: `python compare_roundtrip.py corpus/sample08_int_ops.exe roundtrip/sample08_int_ops.exe`
   or `python compare_roundtrip.py --all roundtrip`.

Notes: local names are neutral (`loc<i>`, `glob<id>`); they are not stored in the exe, so the new exe
must have the same descriptor order. `;;inferred` notes are comments; the statements they annotate are
the riskiest ones if a mismatch shows up.

## Samples (simplest first)
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "roundtrip")
    ap.add_argument("--corpus", help="directory with the sample exes (default ./corpus or $QM_CORPUS)")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    import qmcorpus
    exes = [e for e in qmcorpus.find_exes(a.corpus) if e.stem.startswith("sample")]
    if not exes:
        return 1
    rows_ok, rows_no = [], []
    for e in exes:
        try:
            text, why, n = build(e, a.out)
        except Exception as ex:                      # never crash the batch
            text, why, n = None, [f"decompile failed: {type(ex).__name__}: {ex}"], 0
        if why:
            rows_no.append((e.name, why))
            qp = a.out / (e.stem + ".qml")
            if qp.exists():
                qp.unlink()
            print(f"NOT ROUNDTRIPPABLE {e.stem}: {why[0][:110]}")
        else:
            (a.out / (e.stem + ".qml")).write_bytes(text.encode("utf-8"))
            rows_ok.append((n, e.stem))
            print(f"ok {e.stem} ({n} code lines)")
    rows_ok.sort()
    md = [README_HEAD, "| # | file | code lines | status |", "|---|---|---|---|"]
    for i, (n, st) in enumerate(rows_ok, 1):
        md.append(f"| {i} | roundtrip/{st}.qml | {n} | roundtrippable |")
    md += ["", "### NOT ROUNDTRIPPABLE", "", "| sample | reason |", "|---|---|"]
    for nm, why in rows_no:
        md.append(f"| {nm} | " + "; ".join(why[:3]).replace("|", "/") + " |")
    (a.out / "README.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"roundtrippable {len(rows_ok)} / {len(exes)}; not roundtrippable {len(rows_no)}")


if __name__ == "__main__":
    main()
